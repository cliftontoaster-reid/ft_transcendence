//! The host state backing every plugin store: WASI (a blank context — no
//! filesystem, no env, no stdio) plus the two mediated capabilities, HTTP and
//! log.
//!
//! HTTP is the sandbox-critical one: every request goes through a domain
//! allow-list (exact host or subdomain suffix, same rule as
//! `ImageFetcher`), a timeout, a response size cap, and a store-level
//! memory limit. Errors come back to the *guest* as strings — a plugin
//! failing to reach its API is a plugin-level failure the host degrades to
//! a warning, never a host crash.

use std::path::PathBuf;
use std::sync::Arc;
use std::time::Duration;

use wasmtime::StoreLimitsBuilder;

use crate::bindings::dionysus::metadata::host::{Host, HttpMethod, HttpResponse};
use crate::plugin::PluginOptions;

/// Default domains plugins may talk to. Suffix match: `tmdb.org` also
/// allows `image.tmdb.org`, but not `eviltmdb.org`.
pub const DEFAULT_PLUGIN_DOMAINS: &[&str] = &[
  "tvmaze.com",
  "tmdb.org",
  "omdbapi.com",
  "media-amazon.com",
  "fanart.tv",
  "thetvdb.com",
  "tvrage.com",
  "wikipedia.org",
  "wikidata.org",
];

/// Exact host match or subdomain match against a listed suffix.
pub(crate) fn domain_allowed(allowed: &[String], host: &str) -> bool {
  allowed.iter().any(|allowed| {
    let allowed = allowed.to_lowercase();
    host == allowed || host.ends_with(&format!(".{allowed}"))
  })
}

pub(crate) struct HostState {
  pub(crate) wasi: wasmtime_wasi::WasiCtx,
  pub(crate) table: wasmtime_wasi::ResourceTable,
  pub(crate) limits: wasmtime::StoreLimits,
  client: reqwest::Client,
  options: Arc<PluginOptions>,
  plugin: String,
}

/// `WasiCtx`/`ResourceTable` are `Send` but not `Sync`, while the async
/// host functions generated by `bindgen!` hold `&HostState` across awaits
/// (hence `Sync`). This is sound because each `HostState` lives inside one
/// plugin's `Store`, which is only ever reached through that plugin's
/// async `Mutex` in `WasmProvider`: at most one thread can be inside the
/// state at any time, and the state is never aliased as `&HostState` from
/// two threads concurrently.
unsafe impl Sync for HostState {}

impl HostState {
  pub(crate) fn new(options: Arc<PluginOptions>, plugin: String) -> Self {
    let client = reqwest::Client::builder()
      .timeout(options.http_timeout)
      .build()
      .expect("reqwest client");
    Self {
      wasi: wasmtime_wasi::WasiCtxBuilder::new().build(),
      table: wasmtime_wasi::ResourceTable::new(),
      limits: StoreLimitsBuilder::new()
        .memory_size(options.max_memory_bytes)
        .build(),
      client,
      options,
      plugin,
    }
  }

  pub(crate) fn limiter(&mut self) -> &mut wasmtime::StoreLimits {
    &mut self.limits
  }

  async fn http_request_inner(
    &self,
    method: HttpMethod,
    url: &str,
    headers: Vec<(String, String)>,
    body: Option<Vec<u8>>,
  ) -> Result<HttpResponse, String> {
    let parsed = reqwest::Url::parse(url).map_err(|e| format!("invalid url {url}: {e}"))?;
    if !matches!(parsed.scheme(), "http" | "https") {
      return Err(format!("unsupported scheme {}", parsed.scheme()));
    }
    let host = parsed.host_str().unwrap_or_default().to_lowercase();
    if !domain_allowed(&self.options.allowed_domains, &host) {
      return Err(format!("domain not allowed: {host}"));
    }

    let method = match method {
      HttpMethod::Get => reqwest::Method::GET,
      HttpMethod::Post => reqwest::Method::POST,
    };
    let mut request = self
      .client
      .request(method, parsed)
      .timeout(self.options.http_timeout);
    for (name, value) in headers {
      let name = reqwest::header::HeaderName::from_bytes(name.as_bytes())
        .map_err(|e| format!("header name: {e}"))?;
      let value = reqwest::header::HeaderValue::from_str(&value)
        .map_err(|e| format!("header value: {e}"))?;
      request = request.header(name, value);
    }
    if let Some(body) = body {
      request = request.body(body);
    }

    let mut response = request.send().await.map_err(|e| format!("request failed: {e}"))?;
    let status = response.status().as_u16();
    let mut bytes = Vec::new();
    while let Some(chunk) = response.chunk().await.map_err(|e| format!("read failed: {e}"))? {
      if bytes.len() + chunk.len() > self.options.max_response_bytes {
        return Err(format!(
          "response exceeds the {} byte cap",
          self.options.max_response_bytes
        ));
      }
      bytes.extend_from_slice(&chunk);
    }
    tracing::debug!(plugin = %self.plugin, %url, %status, bytes = bytes.len(), "plugin http");
    Ok(HttpResponse { status, body: bytes })
  }
}

impl wasmtime_wasi::WasiView for HostState {
  fn ctx(&mut self) -> wasmtime_wasi::WasiCtxView<'_> {
    wasmtime_wasi::WasiCtxView { ctx: &mut self.wasi, table: &mut self.table }
  }
}

impl Host for HostState {
  async fn http_request(
    &mut self,
    method: HttpMethod,
    url: String,
    headers: Vec<(String, String)>,
    body: Option<Vec<u8>>,
  ) -> wasmtime::Result<Result<HttpResponse, String>> {
    let result = self.http_request_inner(method, &url, headers, body).await;
    if let Err(err) = &result {
      tracing::debug!(plugin = %self.plugin, %url, %err, "plugin http denied or failed");
    }
    Ok(result)
  }

  async fn log(&mut self, level: u8, message: String) -> wasmtime::Result<()> {
    let plugin = self.plugin.as_str();
    match level {
      0 => tracing::error!(plugin, "{message}"),
      1 => tracing::warn!(plugin, "{message}"),
      2 => tracing::info!(plugin, "{message}"),
      3 => tracing::debug!(plugin, "{message}"),
      _ => tracing::trace!(plugin, "{message}"),
    }
    Ok(())
  }
}

/// Where `METADATA_TRACE_DIR` writes pretty JSON dumps of every payload
/// crossing the boundary. A debugging aid, never load-bearing.
pub(crate) struct Trace {
  dir: Option<PathBuf>,
  seq: std::sync::atomic::AtomicU64,
}

impl Trace {
  pub(crate) fn new(dir: Option<PathBuf>) -> Self {
    if let Some(dir) = &dir
      && let Err(err) = std::fs::create_dir_all(dir)
    {
      tracing::warn!(dir = %dir.display(), %err, "trace dir unusable, tracing disabled");
      return Self { dir: None, seq: std::sync::atomic::AtomicU64::new(0) };
    }
    Self { dir, seq: std::sync::atomic::AtomicU64::new(0) }
  }

  /// Dump one payload as pretty JSON: `{plugin}.{op}.{in|out}.{seq}.json`.
  /// Failures are ignored — this is a debug aid, not a feature.
  pub(crate) fn dump<T: serde::Serialize>(&self, plugin: &str, op: &str, direction: &str, payload: &T) {
    let Some(dir) = &self.dir else { return };
    let Ok(json) = serde_json::to_string_pretty(payload) else { return };
    let seq = self.seq.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
    let file = format!("{}.{op}.{direction}.{seq:04}.json", sanitize(plugin));
    let _ = std::fs::write(dir.join(file), json);
  }
}

/// Keep plugin-provided ids filesystem-safe in trace file names.
fn sanitize(name: &str) -> String {
  let cleaned: String = name
    .chars()
    .map(|c| if c.is_ascii_alphanumeric() || c == '-' || c == '_' { c } else { '_' })
    .collect();
  if cleaned.is_empty() { "plugin".to_string() } else { cleaned }
}

/// Plugin ids should be short, stable slugs; anything else can't be used
/// as a registry key or a file name.
pub(crate) fn id_is_sane(id: &str) -> bool {
  !id.is_empty()
    && id.len() <= 64
    && id.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
}

