pub(crate) const DEFAULT_MAX_MEMORY_BYTES: usize = 64 * 1024 * 1024;

#[cfg(test)]
mod tests {
  use super::*;

  fn allow(list: &[&str]) -> Vec<String> {
    list.iter().map(|d| d.to_string()).collect()
  }

  #[test]
  fn domain_allow_list_matches_subdomain_suffix() {
    let domains = allow(&["tmdb.org", "media-amazon.com"]);
    assert!(domain_allowed(&domains, "image.tmdb.org"));
    assert!(domain_allowed(&domains, "tmdb.org"));
    assert!(domain_allowed(&domains, "m.media-amazon.com"));
    assert!(!domain_allowed(&domains, "eviltmdb.org"));
    assert!(!domain_allowed(&domains, "example.com"));
    assert!(!domain_allowed(&domains, "org"));
  }

  #[test]
  fn domain_check_is_case_insensitive_on_the_listing() {
    let domains = allow(&["TMDB.org"]);
    assert!(domain_allowed(&domains, "image.tmdb.org"));
  }

  #[test]
  fn id_sanity() {
    assert!(id_is_sane("tvmaze"));
    assert!(id_is_sane("my-source_2"));
    assert!(!id_is_sane(""));
    assert!(!id_is_sane("has spaces"));
    assert!(!id_is_sane("path/../escape"));
    assert!(!id_is_sane(&"x".repeat(65)));
  }

  #[test]
  fn sanitize_never_produces_empty_names() {
    assert_eq!(sanitize("tmdb"), "tmdb");
    assert_eq!(sanitize("../etc"), ".._etc".replace('.', "_"));
    assert_eq!(sanitize(""), "plugin");
  }
}
