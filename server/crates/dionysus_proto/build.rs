use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

fn find_protos(dir: &Path, out: &mut Vec<PathBuf>) {
  for entry in fs::read_dir(dir).unwrap() {
    let p = entry.unwrap().path();
    if p.is_dir() {
      find_protos(&p, out);
    } else if p.extension().is_some_and(|e| e == "proto") {
      out.push(p);
    }
  }
}

#[derive(Default)]
struct ModuleTree {
  package: Option<String>,
  children: BTreeMap<String, ModuleTree>,
}

impl ModuleTree {
  fn insert(&mut self, package: &str) {
    let mut node = self;
    for part in package.split('.') {
      node = node.children.entry(part.to_owned()).or_default();
    }
    node.package = Some(package.to_owned());
  }
}

fn write_module(out: &mut String, name: &str, node: &ModuleTree, depth: usize) {
  let indent = "  ".repeat(depth);
  writeln!(out, "{indent}pub mod {name} {{").unwrap();
  if let Some(package) = &node.package {
    writeln!(out, "{indent}  tonic::include_proto!(\"{package}\");").unwrap();
  }
  for (child, subtree) in &node.children {
    write_module(out, child, subtree, depth + 1);
  }
  writeln!(out, "{indent}}}").unwrap();
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
  let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR")?);
  let repo_root = manifest.join("../../..").canonicalize()?;
  let proto_root = repo_root.join("proto");
  let googleapis = repo_root.join("third_party/googleapis");
  let out_dir = PathBuf::from(std::env::var("OUT_DIR")?);

  // The module tree is derived from the generated files, so clear previous
  // outputs to avoid exposing packages that no longer exist.
  for entry in fs::read_dir(&out_dir)? {
    let path = entry?.path();
    if path.extension().is_some_and(|e| e == "rs") {
      fs::remove_file(path)?;
    }
  }

  let mut protos = Vec::new();
  find_protos(&proto_root, &mut protos);
  protos.sort();

  tonic_prost_build::configure()
    .build_client(true)
    .build_server(true)
    .compile_protos(&protos, &[proto_root.clone(), googleapis.clone()])?;

  let mut packages = Vec::new();
  for entry in fs::read_dir(&out_dir)? {
    let path = entry?.path();
    if path.extension().is_some_and(|e| e == "rs") {
      if let Some(stem) = path.file_stem() {
        packages.push(stem.to_string_lossy().into_owned());
      }
    }
  }
  packages.sort();

  let mut tree = ModuleTree::default();
  for package in packages {
    tree.insert(&package);
  }

  let mut generated = String::from("// @generated by dionysus_proto/build.rs\n");
  for (name, node) in &tree.children {
    write_module(&mut generated, name, node, 0);
  }
  fs::write(out_dir.join("proto_tree.rs"), generated)?;

  println!("cargo:rerun-if-changed={}", proto_root.display());
  println!("cargo:rerun-if-changed={}", googleapis.display());
  Ok(())
}
